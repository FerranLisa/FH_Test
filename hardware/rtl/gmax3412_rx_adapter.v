// FH_Carrier adapter for the Gpixel 16-lane Sub-LVDS training receiver.
//
// Current scope:
//   - 16 data lanes, 2 source-synchronous clocks
//   - 10-bit mode, 16 channels
//   - Table-16 training word 10'h165
//   - 1.20 Gb/s serial rate -> 120 MHz parallel word clock
//   - automatic/retry training after the sensor clocks become active
//   - FH-3 reset-domain cleanup: training/clock module owns all receive-domain resets
//
// The aligned 16 x 12-bit words are exposed as image_data (10 LSBs valid in
// 10-bit mode). The full-frame decoder qualifies physical DMA samples.

module gmax3412_rx_adapter #(parameter integer MAX_SKEW=1)
(
    input  wire         rst_n,

    input  wire         clk0_p,
    input  wire         clk0_n,
    input  wire         clk1_p,
    input  wire         clk1_n,

    input  wire [15:0]  data_p,
    input  wire [15:0]  data_n,

    input  wire [3:0]   debug_word_index,
    input  wire         debug_lane_select,
    input  wire         debug_freeze,

    output wire [15:0]  training_result,
    output wire         training_done,

    output wire [9:0]   debug_word,
    output wire         debug_word_valid,
    output wire         debug_clk0_activity,
    output wire         debug_clk1_activity,
    output wire         debug_lane_activity,

    output wire         pixel_clk,
    output wire         frame_valid,
    output wire         line_valid,
    output wire [191:0] image_data
);

    localparam [11:0] GMAX_TRAINING_WORD = 12'h165;
    localparam [1:0]  GMAX_BIT_WIDTH     = 2'b10; // Gpixel encoding: 2 = 10 bit
    localparam [3:0]  GMAX_CHAN_NUM      = 4'd8;  // Gpixel encoding: 8 = 16 channels

    wire        clk_rxg;
    wire        training_done_raw;
    wire [15:0] training_result_raw;
    (* MARK_DEBUG = "TRUE" *) wire [191:0] data_train;

    // One reset chain per receive domain.  training.v exports the already
    // synchronized 120 MHz reset generated by gmax3412_iob_clock.
    wire rst_rxg_ctrl;
    wire [9:0] training_debug_word;

    // V16.3: debug_freeze originates in the AXI GPIO / clk_pl_0 domain and
    // controls the automatic retry FSM in clk_rxg (~120 MHz). Use the AMD XPM
    // primitive rather than a hand-written 2-FF chain so Vivado recognizes this
    // as an intentional asynchronous CDC and applies the XPM timing exception
    // to the source-to-first-stage path. This remains the ONE freeze synchronizer
    // in the design; training.v must not synchronize debug_freeze again.
    wire debug_freeze_rxg;

    xpm_cdc_single #(
        .DEST_SYNC_FF   (2),
        .INIT_SYNC_FF   (0),
        .SIM_ASSERT_CHK (0),
        .SRC_INPUT_REG  (0)
    ) u_xpm_cdc_debug_freeze (
        .dest_out (debug_freeze_rxg),
        .dest_clk (clk_rxg),
        // SRC_INPUT_REG=0 because the AXI GPIO output is already registered.
        .src_clk  (1'b0),
        .src_in   (debug_freeze)
    );

    // Automatic training controller. If STREAM_EN is not active yet, an
    // early attempt may fail; the controller retries until all 16 lanes pass.
    localparam [2:0] ST_WAIT      = 3'd0;
    localparam [2:0] ST_PULSE     = 3'd1;
    localparam [2:0] ST_WAIT_DONE = 3'd2;
    localparam [2:0] ST_RETRY     = 3'd3;
    localparam [2:0] ST_LOCKED    = 3'd4;

    reg [2:0]  train_state = ST_WAIT;
    reg [15:0] wait_count = 16'd0;
    reg        cmd_start_training = 1'b0;

    always @(posedge clk_rxg) begin
        if (rst_rxg_ctrl) begin
            train_state        <= ST_WAIT;
            wait_count         <= 16'd0;
            cmd_start_training <= 1'b0;
        end else begin
            cmd_start_training <= 1'b0;

            case (train_state)
                ST_WAIT: begin
                    if (debug_freeze_rxg) begin
                        // V16 diagnostic hold: do not launch a new attempt while
                        // software is reading the previous completed snapshot.
                        wait_count <= 16'd0;
                    end else if (wait_count == 16'd2047) begin
                        wait_count         <= 16'd0;
                        cmd_start_training <= 1'b1;
                        train_state        <= ST_PULSE;
                    end else begin
                        wait_count <= wait_count + 1'b1;
                    end
                end

                ST_PULSE: begin
                    // One clk_rxg pulse is sufficient; training.v contains
                    // its own synchronizer/edge detector.
                    train_state <= ST_WAIT_DONE;
                end

                ST_WAIT_DONE: begin
                    if (training_done_raw) begin
                        if (training_result_raw == 16'hFFFF) begin
                            train_state <= ST_LOCKED;
                        end else begin
                            wait_count  <= 16'd0;
                            train_state <= ST_RETRY;
                        end
                    end
                end

                ST_RETRY: begin
                    if (debug_freeze_rxg) begin
                        // Finish any in-flight attempt, then remain here until
                        // software releases the diagnostic snapshot hold.
                        wait_count <= 16'd0;
                    end else if (wait_count == 16'd8191) begin
                        wait_count         <= 16'd0;
                        cmd_start_training <= 1'b1;
                        train_state        <= ST_PULSE;
                    end else begin
                        wait_count <= wait_count + 1'b1;
                    end
                end

                ST_LOCKED: begin
                    // Stay locked until external reset/power-cycle.
                    train_state <= ST_LOCKED;
                end

                default: begin
                    train_state <= ST_WAIT;
                    wait_count  <= 16'd0;
                end
            endcase
        end
    end

    wire [15:0] training_result_dbg = training_result_raw;
    wire        training_done_dbg   = training_done_raw;

    training #(
        .DATA_CHAN_NUM (16),
        .CLK_CHAN_NUM  (2),
        .CHN_PORT_WIDTH(4),
        .DATAIN_SWAP   (16'h0000)
    ) u_training (
        .clk_rxg            (clk_rxg),
        .rst_rxg_out        (rst_rxg_ctrl),
        .reset_n            (rst_n),

        .cmos_ddr_clk_p     ({clk1_p, clk0_p}),
        .cmos_ddr_clk_n     ({clk1_n, clk0_n}),
        .cmos_data_p        (data_p),
        .cmos_data_n        (data_n),

        .reg_bit_width      (GMAX_BIT_WIDTH),
        .reg_chan_num       (GMAX_CHAN_NUM),

        .training_word      (GMAX_TRAINING_WORD),
        .cmd_start_training (cmd_start_training),

        .debug_word_index   (debug_word_index),
        .debug_lane_select  (debug_lane_select),
        .debug_freeze       (debug_freeze_rxg),

        .training_done      (training_done_raw),
        .training_result    (training_result_raw),
        .debug_word         (training_debug_word),
        .debug_word_valid   (debug_word_valid),
        .debug_clk0_activity(debug_clk0_activity),
        .debug_clk1_activity(debug_clk1_activity),
        .debug_lane_activity(debug_lane_activity),

        .dataout            (data_train)
    );

    wire check_arm;
    wire [3:0] check_state;
    wire [159:0] fail_words;
    wire [11:0] fail_row;
    wire [8:0] fail_group;
    wire [3:0] fail_stage;
    wire [2:0] fail_prefix;
    wire [9:0] fail_base;
    // Selector 14 reads a frozen snapshot. A rising lane-select edge
    // advances one field; software holds each level for multiple RX clocks.
    wire read_snapshot, advance;
    xpm_cdc_single #(.DEST_SYNC_FF(3), .SRC_INPUT_REG(0)) snapshot_select_cdc
        (.src_clk(1'b0), .src_in(debug_word_index == 4'd14),
         .dest_clk(clk_rxg), .dest_out(read_snapshot));
    xpm_cdc_single #(.DEST_SYNC_FF(3), .SRC_INPUT_REG(0)) snapshot_advance_cdc
        (.src_clk(1'b0), .src_in(debug_lane_select),
         .dest_clk(clk_rxg), .dest_out(advance));
    reg previous_advance;
    reg [4:0] field;
    always @(posedge clk_rxg) begin
        previous_advance <= advance;
        if (rst_rxg_ctrl || !read_snapshot) field <= 0;
        else if (advance && !previous_advance && field < 21) field <= field + 1'b1;
    end
    reg [9:0] snapshot_word;
    always @* begin
        case (field)
            0: snapshot_word = 10'h319; // Format identifier
            1: snapshot_word = {3'b0,fail_prefix,fail_stage};
            2: snapshot_word = fail_row[9:0];
            3: snapshot_word = {8'b0,fail_row[11:10]};
            4: snapshot_word = {1'b0,fail_group};
            5: snapshot_word = fail_base;
            default: snapshot_word = fail_words[(field-6)*10 +: 10];
        endcase
    end
    xpm_cdc_single #(.DEST_SYNC_FF(3), .SRC_INPUT_REG(0)) check_arm_cdc
        (.src_clk(1'b0), .src_in(debug_word_index == 4'd15),
         .dest_clk(clk_rxg), .dest_out(check_arm));
    wire [191:0] data_aligned;
    wire alignment_error;
    gmax3412_word_align #(.MAX_SKEW(MAX_SKEW)) align_inst (
        .clk(clk_rxg), .reset(rst_rxg_ctrl || train_state != ST_LOCKED),
        .raw_data(data_train), .data(data_aligned), .error(alignment_error));
    gmax3412_ramp_check checker_inst (.clk(clk_rxg), .reset(rst_rxg_ctrl),
        .arm(check_arm), .alignment_error(alignment_error), .data(data_aligned), .state(check_state),
        .snapshot_words(fail_words), .snapshot_row(fail_row), .snapshot_group(fail_group),
        .snapshot_stage(fail_stage), .snapshot_prefix(fail_prefix), .snapshot_base(fail_base));
    assign debug_word = check_arm ? {6'h2a,check_state} :
                        read_snapshot ? snapshot_word : training_debug_word;
    assign training_result = training_result_dbg;
    assign training_done   = training_done_dbg;
    assign pixel_clk       = clk_rxg;
    genvar image_lane;
    generate for(image_lane=0;image_lane<16;image_lane=image_lane+1) begin: pixel10
        assign image_data[12*image_lane+:12]={2'b0,data_aligned[12*image_lane+:10]};
    end endgenerate

    gmax3412_full_frame_sync frame_sync(.clk(clk_rxg), .reset(rst_rxg_ctrl),
        .data(data_aligned), .alignment_error(alignment_error),
        .frame_valid(frame_valid), .line_valid(line_valid));

endmodule

// Acquire on the complete reserved SOF. History retains the prefix and
// early pixels so the decoder receives the entire frame from its first word.
module gmax3412_word_align #(parameter integer MAX_SKEW=1)(
    input wire clk, reset, input wire [191:0] raw_data,
    output wire [191:0] data, output reg error
);
    localparam AGE_BITS = MAX_SKEW < 2 ? 1 : $clog2(MAX_SKEW+1);
    reg [AGE_BITS-1:0] elapsed;
    reg [15:0] seen;
    wire [15:0] sof;
    wire acquire = &(seen | sof) && (|sof);
    reg replay;
    reg [2:0] eof_prefix;
    wire [9:0] lane0 = data[9:0];
    genvar lane;
    generate for (lane=0; lane<16; lane=lane+1) begin: align_lane
        wire [11:0] word_in = raw_data[12*lane+:12];
        reg [2:0] prefix;
        reg [11:0] history [0:MAX_SKEW+3];
        reg [AGE_BITS-1:0] arrival, delay_words;
        integer k;
        always @(posedge clk) begin
            history[0] <= word_in;
            for (k=1; k<=MAX_SKEW+3; k=k+1)
                history[k] <= history[k-1];
            if (reset) prefix <= 0;
            else prefix <= {prefix[1:0] & {2{word_in[9:0]==0}}, &word_in[9:0]};
            if (sof[lane]) arrival <= elapsed;
            if (acquire) delay_words <= sof[lane] ? 0 : elapsed-arrival;
        end
        assign sof[lane] = prefix[2] && word_in[9:0]==10'h200;
        assign data[12*lane+:12] = replay ? history[3+delay_words] : 12'h165;
    end endgenerate
    always @(posedge clk) begin
        error <= 0;
        if (reset) begin
            seen <= 0;
            elapsed <= 0;
            replay <= 0;
            eof_prefix <= 0;
        end else begin
            eof_prefix <= {eof_prefix[1:0] & {2{lane0==0}}, &lane0};
            if (eof_prefix[2] && lane0==10'h274) replay <= 0;
            if (acquire) begin
                replay <= 1;
                seen <= 0;
                elapsed <= 0;
            end else if (|(seen | sof)) begin
                if (elapsed == MAX_SKEW) begin
                    error <= 1;
                    replay <= 0;
                    seen <= 0;
                    elapsed <= 0;
                end else begin
                    seen <= seen | sof;
                    elapsed <= elapsed + 1'b1;
                end
            end
        end
    end
endmodule

// Synchronize the full-window DMA stream independently of the test pattern.
// PIXELS selects the current beat directly, so valid and data have no skew.
module gmax3412_full_frame_sync #(parameter GROUPS=256, ROWS=3072, ROI_ROWS=1024)(
    input wire clk, reset, alignment_error, input wire [191:0] data,
    output wire frame_valid, line_valid
);
    localparam WAIT_SOF=0, PIXELS=1, END_ONES=2, END_ZERO1=3, END_ZERO2=4,
               END_TAG=5, GAP=6, ERROR_BEAT=7;
    reg [2:0] state;
    reg saw_ones, saw_first_zero;
    reg [11:0] row_index;
    reg [8:0] group_index;
    wire [159:0] words;
    genvar lane;
    generate for(lane=0;lane<16;lane=lane+1) begin: unpack
        assign words[10*lane+:10]=data[12*lane+:10];
    end endgenerate
    reg tag_next;
    assign frame_valid = state != WAIT_SOF && state != ERROR_BEAT;
    // The DMA bridge latches geometry error on lval outside fval.
    assign line_valid = state == PIXELS || state == ERROR_BEAT;
    always @(posedge clk) begin
        saw_ones <= &words;
        saw_first_zero <= saw_ones && !(|words);
        tag_next <= saw_first_zero && !(|words);
        if (reset) begin
            state <= WAIT_SOF;
            saw_ones <= 0;
            saw_first_zero <= 0;
            tag_next <= 0;
            row_index <= 0;
            group_index <= 0;
        end else if (alignment_error) begin
            state <= ERROR_BEAT;
        end else case (state)
            WAIT_SOF: if (tag_next && words == {16{10'h200}}) begin
                row_index <= 0;
                group_index <= 0;
                state <= PIXELS;
            end
            PIXELS: if (group_index == GROUPS-1) begin
                group_index <= 0;
                state <= END_ONES;
            end else group_index <= group_index + 1'b1;
            END_ONES: state <= (&words) ? END_ZERO1 : ERROR_BEAT;
            END_ZERO1: state <= !(|words) ? END_ZERO2 : ERROR_BEAT;
            END_ZERO2: state <= !(|words) ? END_TAG : ERROR_BEAT;
            // The physical EOF determines FVAL. The armed DMA bridge checks
            // which of these two legal wire geometries was requested.
            END_TAG: if (words == {16{10'h274}})
                state <= (row_index == ROWS-1 || row_index == ROI_ROWS-1) ? WAIT_SOF : ERROR_BEAT;
            else if (row_index < ROWS-1 && words == {16{10'h0d8}}) begin
                row_index <= row_index + 1'b1;
                state <= GAP;
            end else state <= ERROR_BEAT;
            GAP: if (tag_next) state <= words == {16{10'h2ac}} ? PIXELS : ERROR_BEAT;
            default: state <= WAIT_SOF;
        endcase
    end
endmodule

// One-shot monitor of aligned 10-bit words, before the capture FIFO.
// Table 36 markers occupy four consecutive word clocks on every lane.
// SOF opens line zero and EOF closes the last line (figure 47).
module gmax3412_ramp_check #(parameter GROUPS=256, ROWS=3072)(
    input wire clk, reset, arm, alignment_error,
    input wire [191:0] data,
    output reg [3:0] state,
    output reg [159:0] snapshot_words,
    output reg [11:0] snapshot_row,
    output reg [8:0] snapshot_group,
    output reg [3:0] snapshot_stage,
    output reg [2:0] snapshot_prefix,
    output reg [9:0] snapshot_base
);
    localparam IDLE=0, WAIT_SOF=1, PIXELS=2, END_PREFIX=3, END_ZERO1=4,
               END_ZERO2=5, END_TAG=6, GAP=7, PASS=8, BAD_SYNC=9, BAD_DATA=10, BAD_ALIGNMENT=11;
    reg [2:0] prefix;
    reg [8:0] group_index;
    reg [11:0] row_index;
    reg [9:0] origin;
    wire [159:0] words;
    wire [15:0] mismatch;
    // Establish the crop's ramp phase once, on the first group. Lane 1
    // avoids the zero reserved by Sub-LVDS at the relative origin.
    wire first = row_index == 0 && group_index == 0;
    wire [9:0] phase = first ? data[12 +: 10] - 10'd1 : origin;
    genvar lane;
    generate for (lane=0; lane<16; lane=lane+1) begin: compare_lane
        wire [9:0] sample = data[12*lane +: 10];
        wire [9:0] expected = phase + row_index + (group_index << 4) + lane;
        assign words[10*lane +: 10] = sample;
        // Datasheet specifies nonzero output at wrap, without defining its code.
        assign mismatch[lane] = expected == 0 ? sample == 0 : sample != expected;
    end endgenerate
    wire ones_word = &words;
    wire zero_word = ~|words;
    wire idle_word = words == {16{10'h165}};
    // Save the beat evaluated by the FSM. A transition to a terminal
    // state freezes this very beat, including through disarm and readout.
    always @(posedge clk) begin
        if (!reset && arm && state >= WAIT_SOF && state <= GAP) begin
            snapshot_words <= words;
            snapshot_row <= row_index;
            snapshot_group <= (state >= END_PREFIX && state <= END_TAG) ? GROUPS : group_index;
            snapshot_stage <= state;
            snapshot_prefix <= prefix;
            snapshot_base <= phase + row_index + (group_index << 4);
        end
    end
    always @(posedge clk) begin
        if (reset || !arm) begin
            state <= IDLE;
            prefix <= 0;
            group_index <= 0;
            row_index <= 0;
            origin <= 0;
        end else if (alignment_error && state == WAIT_SOF) begin
            state <= BAD_ALIGNMENT;
        end else case (state)
            IDLE: state <= WAIT_SOF;
            WAIT_SOF, GAP: case (prefix)
                0: if (ones_word) prefix <= 1;
                   else if (!idle_word) state <= BAD_SYNC;
                1,2: if (zero_word) prefix <= prefix + 1'b1;
                     else state <= BAD_SYNC;
                3: if (words == (state == WAIT_SOF ? {16{10'h200}} : {16{10'h2ac}})) begin
                       state <= PIXELS;
                       prefix <= 0;
                   end else state <= BAD_SYNC;
                default: state <= BAD_SYNC;
            endcase
            PIXELS: begin
                if (first) origin <= phase;
                if (|mismatch) state <= BAD_DATA;
                else if (group_index == GROUPS-1) begin
                    group_index <= 0;
                    state <= END_PREFIX;
                end else group_index <= group_index + 1'b1;
            end
            END_PREFIX: state <= ones_word ? END_ZERO1 : BAD_SYNC;
            END_ZERO1: state <= zero_word ? END_ZERO2 : BAD_SYNC;
            END_ZERO2: state <= zero_word ? END_TAG : BAD_SYNC;
            END_TAG: if (row_index == ROWS-1)
                         state <= words == {16{10'h274}} ? PASS : BAD_SYNC;
                     else if (words == {16{10'h0d8}}) begin
                         row_index <= row_index + 1'b1;
                         state <= GAP;
                     end else state <= BAD_SYNC;
            default: state <= state; // Terminal until the next disarm.
        endcase
    end
endmodule
